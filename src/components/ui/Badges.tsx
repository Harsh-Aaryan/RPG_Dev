import { FlaskConical, Radio, ScrollText, Sparkle } from 'lucide-react';
import { SEVERITY_STYLE } from '../../lib/game-rules';
import type { QuestSource, Severity } from '../../lib/types';
import { SeveritySigil, ThreatPips } from '../art/Sigils';

/** Severity as sigil + label + threat pips — never colour alone. */
export function SeverityBadge({ severity, size = 'sm' }: { severity: Severity; size?: 'sm' | 'md' }) {
  const s = SEVERITY_STYLE[severity];
  return (
    <span className={`tag ${s.border} ${size === 'md' ? 'px-2 py-1 text-sm' : ''}`} title={`${s.label} severity`}>
      <SeveritySigil severity={severity} size={size === 'md' ? 16 : 14} className={s.text} />
      <span className="font-semibold text-ink">{s.label}</span>
      <ThreatPips severity={severity} className={s.text} />
    </span>
  );
}

/** Honesty label for quest text: live Gemma output or the hand-written template. */
export function SourceBadge({ source, model, long = false }: { source: QuestSource; model?: string; long?: boolean }) {
  return source === 'gemma' ? (
    <span className="tag" title={model ? `Generated by ${model}` : 'Generated by Gemma 4'}>
      <Sparkle size={12} className="text-copper" aria-hidden /> Gemma 4 · live
    </span>
  ) : (
    <span className="tag text-ink-3" title="Gemma unavailable, so this is a hand-written template">
      <ScrollText size={12} aria-hidden /> {long ? 'Template (Gemma unavailable)' : 'Template'}
    </span>
  );
}

export function ScanLabel({ label }: { label: 'simulated' | 'live' }) {
  return label === 'simulated' ? (
    <span className="tag border-gold/40" title="Findings come from the mock Strix worker, not a real Strix run">
      <FlaskConical size={12} className="text-gold" aria-hidden /> Simulated Strix scan
    </span>
  ) : (
    <span className="tag border-sage/45">
      <Radio size={12} className="text-sage" aria-hidden /> Live Strix scan
    </span>
  );
}
